import SwiftUI
import AppKit
import Combine
import CryptoKit

// MARK: - Запись в истории буфера обмена

struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image }

    let id: UUID
    let kind: Kind
    /// Текст (для .text)
    var text: String?
    /// Имя файла картинки в папке приложения (для .image)
    var imageFile: String?
    /// Отпечаток содержимого, чтобы не хранить дубликаты
    let fingerprint: String
    var date: Date
    var isPinned = false
}

// MARK: - Слежение за буфером обмена

final class ClipboardHistory: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    /// changeCount после нашей собственной записи — её не считаем новой копией
    private var ownChangeCount: Int?
    private let images = NSCache<NSString, NSImage>()

    private var isEnabled: Bool {
        UserDefaults.standard.object(forKey: "clipboardHistory") as? Bool ?? true
    }
    private var limit: Int {
        let value = UserDefaults.standard.integer(forKey: "clipboardLimit")
        return value > 0 ? value : 30
    }

    private let folder: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let url = base.appendingPathComponent("RequiemNotch/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }()
    private var indexFile: URL { folder.appendingPathComponent("history.json") }

    // MARK: Запуск

    func start() {
        load()
        // macOS не сообщает об изменении буфера — проверяем счётчик дважды в секунду
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
        timer?.tolerance = 0.2
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        // Это мы сами положили запись обратно в буфер
        if pasteboard.changeCount == ownChangeCount { return }
        guard isEnabled else { return }

        // Пароли и временные данные (1Password, Bitwarden, Связка ключей) не сохраняем
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType",
                                         "org.nspasteboard.TransientType",
                                         "org.nspasteboard.AutoGeneratedType",
                                         "com.agilebits.onepassword"]
        guard types.isDisjoint(with: privateTypes) else { return }

        // Скопировали файлы в Finder — это не текст, пропускаем
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) { return }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(text: text)
        } else if let image = NSImage(pasteboard: pasteboard) {
            add(image: image)
        }
    }

    // MARK: Добавление

    private func add(text: String) {
        let fingerprint = "t:" + Self.digest(Data(text.utf8))
        if bumpExisting(fingerprint) { return }
        insert(ClipboardItem(id: UUID(), kind: .text, text: text,
                             fingerprint: fingerprint, date: Date()))
    }

    private func add(image: NSImage) {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return }
        // Огромные скриншоты не храним: больше 15 МБ
        guard png.count < 15_000_000 else { return }

        let fingerprint = "i:" + Self.digest(png)
        if bumpExisting(fingerprint) { return }

        let id = UUID()
        let name = "\(id.uuidString).png"
        do { try png.write(to: folder.appendingPathComponent(name)) } catch { return }
        images.setObject(image, forKey: name as NSString)
        insert(ClipboardItem(id: id, kind: .image, imageFile: name,
                             fingerprint: fingerprint, date: Date()))
    }

    /// Стабильный отпечаток (не меняется между запусками, в отличие от hashValue)
    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    /// Такая запись уже есть — поднимаем её наверх вместо дубликата
    private func bumpExisting(_ fingerprint: String) -> Bool {
        guard let index = items.firstIndex(where: { $0.fingerprint == fingerprint }) else { return false }
        var item = items.remove(at: index)
        item.date = Date()
        withAnimation(NotchAnimation.content) { items.insert(item, at: insertionIndex) }
        save()
        return true
    }

    /// Закреплённые всегда сверху, новые — сразу под ними
    private var insertionIndex: Int { items.filter(\.isPinned).count }

    private func insert(_ item: ClipboardItem) {
        withAnimation(NotchAnimation.content) {
            items.insert(item, at: insertionIndex)
            trim()
        }
        save()
    }

    /// Убрать самые старые незакреплённые записи сверх лимита
    private func trim() {
        while items.count > limit, let index = items.lastIndex(where: { !$0.isPinned }) {
            deleteFile(of: items.remove(at: index))
        }
    }

    // MARK: Действия

    /// Положить запись обратно в буфер обмена
    func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount

        // Использованная запись поднимается наверх
        if let index = items.firstIndex(where: { $0.id == item.id }), !item.isPinned {
            var moved = items.remove(at: index)
            moved.date = Date()
            withAnimation(NotchAnimation.content) { items.insert(moved, at: insertionIndex) }
            save()
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var changed = items.remove(at: index)
        changed.isPinned.toggle()
        withAnimation(NotchAnimation.content) {
            items.insert(changed, at: changed.isPinned ? 0 : insertionIndex)
        }
        save()
    }

    func remove(_ item: ClipboardItem) {
        withAnimation(NotchAnimation.content) { items.removeAll { $0.id == item.id } }
        deleteFile(of: item)
        save()
    }

    /// Очистить всё, кроме закреплённых
    func clear() {
        let removed = items.filter { !$0.isPinned }
        withAnimation(NotchAnimation.content) { items.removeAll { !$0.isPinned } }
        removed.forEach(deleteFile)
        save()
    }

    func image(for item: ClipboardItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = images.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: folder.appendingPathComponent(name)) else { return nil }
        images.setObject(image, forKey: name as NSString)
        return image
    }

    // MARK: Хранение

    private func deleteFile(of item: ClipboardItem) {
        guard let name = item.imageFile else { return }
        images.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: folder.appendingPathComponent(name))
    }

    private func save() {
        let snapshot = items
        let url = indexFile
        DispatchQueue.global(qos: .utility).async {
            if let data = try? JSONEncoder().encode(snapshot) {
                try? data.write(to: url, options: .atomic)
            }
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexFile),
              let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        // Картинки, файлы которых пропали, отбрасываем
        items = saved.filter { item in
            guard let name = item.imageFile else { return true }
            return FileManager.default.fileExists(atPath: folder.appendingPathComponent(name).path)
        }
    }
}

// MARK: - История буфера в острове

struct ClipboardView: View {
    @EnvironmentObject var clipboard: ClipboardHistory
    let height: CGFloat

    var body: some View {
        ZStack {
            RoundedRectangle(cornerRadius: 14)
                .fill(.white.opacity(0.08))

            if clipboard.items.isEmpty {
                VStack(spacing: 6) {
                    Image(systemName: "doc.on.clipboard")
                        .font(.system(size: 20))
                    Text("Copied text and images appear here")
                        .font(.caption)
                        .multilineTextAlignment(.center)
                }
                .foregroundStyle(.secondary)
                .padding(.horizontal, 20)
                .transition(.blurFade)
            } else {
                ScrollView(.vertical, showsIndicators: false) {
                    LazyVStack(spacing: 4) {
                        ForEach(clipboard.items) { item in
                            ClipboardRow(item: item)
                                .transition(.blurFade)
                        }
                    }
                    .padding(6)
                }
            }
        }
        .frame(width: 264, height: height)
        .clipShape(RoundedRectangle(cornerRadius: 14))
        .overlay(alignment: .topTrailing) {
            if clipboard.items.contains(where: { !$0.isPinned }) {
                Button { clipboard.clear() } label: {
                    Image(systemName: "xmark.circle.fill")
                }
                .buttonStyle(.pressable)
                .foregroundStyle(.secondary)
                .help("Clear history")
                .padding(6)
            }
        }
        .animation(NotchAnimation.content, value: clipboard.items.isEmpty)
    }
}

// MARK: - Одна запись

private struct ClipboardRow: View {
    let item: ClipboardItem
    @EnvironmentObject var clipboard: ClipboardHistory
    @State private var hovering = false
    @State private var copied = false

    var body: some View {
        HStack(spacing: 8) {
            preview

            Spacer(minLength: 0)

            if copied {
                Image(systemName: "checkmark.circle.fill")
                    .foregroundStyle(.green)
                    .transition(.scale.combined(with: .opacity))
            } else if hovering || item.isPinned {
                HStack(spacing: 6) {
                    Button { clipboard.togglePin(item) } label: {
                        Image(systemName: item.isPinned ? "pin.fill" : "pin")
                    }
                    .help(item.isPinned ? "Unpin" : "Pin")
                    if hovering {
                        Button { clipboard.remove(item) } label: {
                            Image(systemName: "trash")
                        }
                        .help("Remove")
                    }
                }
                .buttonStyle(.pressable)
                .foregroundStyle(item.isPinned && !hovering ? Color.white : Color.secondary)
                .transition(.opacity)
            }
        }
        .font(.system(size: 11))
        .padding(.horizontal, 8)
        .padding(.vertical, 5)
        .frame(minHeight: 30)
        .background(
            RoundedRectangle(cornerRadius: 8)
                .fill(.white.opacity(hovering ? 0.12 : 0.04))
        )
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
        .onTapGesture {
            clipboard.copy(item)
            withAnimation(.spring(response: 0.25)) { copied = true }
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.9) {
                withAnimation(.easeOut(duration: 0.2)) { copied = false }
            }
        }
        .help("Click to copy")
        .animation(.easeOut(duration: 0.12), value: hovering)
    }

    @ViewBuilder private var preview: some View {
        switch item.kind {
        case .text:
            Text(verbatim: item.text?
                    .trimmingCharacters(in: .whitespacesAndNewlines)
                    .replacingOccurrences(of: "\n", with: " ") ?? "")
                .lineLimit(2)
                .foregroundStyle(.white)
        case .image:
            HStack(spacing: 8) {
                if let image = clipboard.image(for: item) {
                    Image(nsImage: image)
                        .resizable()
                        .aspectRatio(contentMode: .fill)
                        .frame(width: 44, height: 28)
                        .clipShape(RoundedRectangle(cornerRadius: 5))
                }
                Text("Image")
                    .foregroundStyle(.secondary)
            }
        }
    }
}
